"""Generate reviewed canonical seed SQL; never connects to a database."""

import json
from pathlib import Path
from app.models import PilotDataset

ROOT = Path(__file__).resolve().parents[2]


def seed_sql():
    dataset = PilotDataset.model_validate_json(
        (ROOT / "backend/app/data/yogyakarta-v0.4.0.json").read_text(encoding="utf8")
    )
    rows = json.dumps(
        [
            {
                "dataset_version": dataset.datasetVersion,
                "place": p.model_dump(mode="json"),
            }
            for p in dataset.places
        ],
        ensure_ascii=False,
    )
    assert "$tripin_seed$" not in rows
    return (
        """-- Generated by backend/scripts/export_catalog_seed.py; no invented metadata.
-- Non-destructive: identical re-run is allowed, conflicting existing records fail.
begin;
create temporary table tripin_seed_rows on commit drop as
select dataset_version, place from jsonb_to_recordset($tripin_seed$"""
        + rows
        + """$tripin_seed$::jsonb)
  as seed(dataset_version text, place jsonb);
do $$ begin
  if exists (
    select 1 from public.tripin_place_catalog existing join tripin_seed_rows seed
      on existing.dataset_version = seed.dataset_version and existing.place_id = seed.place->>'id'
      where existing.place <> seed.place
  ) then raise exception 'Catalog version conflict: existing row differs; review and use a new dataset version'; end if;
end $$;
insert into public.tripin_place_catalog(dataset_version, place)
  select dataset_version, place from tripin_seed_rows
  on conflict (dataset_version, place_id) do nothing;
commit;
"""
    )


if __name__ == "__main__":
    (ROOT / "supabase/seed.sql").write_text(seed_sql(), encoding="utf8")
